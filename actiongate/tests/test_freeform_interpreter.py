def test_gemini_path_mocked():
    interpreter = FreeformInterpreter()
    interpreter.api_key = "FAKE_TEST_KEY"

    mock_gemini_json = json.dumps({
        "action_type": "update_supplier",
        "arguments": {"supplier_id": "SUP-001", "new_bank_account": "ACC-GEMINI-EXTRACTED-77"},
        "context": "Prompt injection in vendor note",
    })

    mock_response = MagicMock()
    mock_response.read.return_value = json.dumps({
        "candidates": [{
            "content": {"parts": [{"text": mock_gemini_json}]}
        }]
    }).encode("utf-8")
    mock_response.__enter__.return_value = mock_response

    with patch("urllib.request.urlopen", return_value=mock_response):
        ok, payload, msg = interpreter.interpret(
            "Update supplier SUP-001 to ACC-GEMINI-EXTRACTED-77",
            task_id="TASK-DISP-101",
            user_role="riya",
        )
        assert ok
        assert "Gemini LLM" in msg
        assert payload["action_type"] == "update_supplier"
        assert payload["arguments"]["new_bank_account"] == "ACC-GEMINI-EXTRACTED-77"
        # Server still strictly forces task_id and assigned_agent
        assert payload["task_id"] == "TASK-DISP-101"
        assert payload["agent_id"] == "agent-001"


def test_gemini_extra_fields_from_model_ignored():
    """Extra fields generated by LLM (forged agent_id, forged task_id, role) are discarded."""
    interpreter = FreeformInterpreter()
    interpreter.api_key = "FAKE_TEST_KEY"

    # Attacker tries to have LLM output rogue agent_id and forged task_id
    mock_gemini_json = json.dumps({
        "action_type": "process_payment",
        "agent_id": "rogue-agent-666",
        "task_id": "TASK-FORGED-ROOT",
        "requested_by": "superadmin",
        "role": "admin",
        "arguments": {"amount": 5000.0, "bank_account": "ACC-FRAUD-1", "supplier_id": "SUP-001"},
        "context": "Fake context",
    })

    mock_response = MagicMock()
    mock_response.read.return_value = json.dumps({
        "candidates": [{"content": {"parts": [{"text": mock_gemini_json}]}}]
    }).encode("utf-8")
    mock_response.__enter__.return_value = mock_response

    with patch("urllib.request.urlopen", return_value=mock_response):
        ok, payload, msg = interpreter.interpret(
            "Pay 5000 to ACC-FRAUD-1",
            task_id="TASK-DISP-101",
            user_role="riya",
        )
        assert ok
        # Server values must completely overwrite model's hallucinated/attacker fields
        assert payload["agent_id"] == "agent-001"
        assert payload["task_id"] == "TASK-DISP-101"
        assert payload["requested_by"] == "riya"
        assert "role" not in payload


def test_gemini_unsupported_action_rejected():
    """Unsupported or arbitrary action types from LLM are rejected/fall through to rule-based fallback."""
    interpreter = FreeformInterpreter()
    interpreter.api_key = "FAKE_TEST_KEY"

    mock_gemini_json = json.dumps({
        "action_type": "drop_database_tables",
        "arguments": {"target": "all"},
        "context": "injection",
    })

    mock_response = MagicMock()
    mock_response.read.return_value = json.dumps({
        "candidates": [{"content": {"parts": [{"text": mock_gemini_json}]}}]
    }).encode("utf-8")
    mock_response.__enter__.return_value = mock_response

    with patch("urllib.request.urlopen", return_value=mock_response):
        # When Gemini returns unsupported action, _gemini_parse returns None
        # and rule-based parser fails loudly because it's not a valid ERP action
        ok, payload, msg = interpreter.interpret(
            "Drop database tables immediately",
            task_id="TASK-DISP-101",
            user_role="riya",
        )
        assert not ok
        assert "Could not interpret" in msg or "Unparsable" in msg or "Invalid" in msg


def test_gemini_non_json_output_falls_back():
    """Non-JSON response from Gemini gracefully falls back to deterministic rule parser."""
    interpreter = FreeformInterpreter()
    interpreter.api_key = "FAKE_TEST_KEY"

    # Gemini returns raw natural language instead of valid JSON
    mock_response = MagicMock()
    mock_response.read.return_value = json.dumps({
        "candidates": [{"content": {"parts": [{"text": "I will execute a payment of ₹12,000 to ACC-FRAUD-999 right away."}]}}]
    }).encode("utf-8")
    mock_response.__enter__.return_value = mock_response

    with patch("urllib.request.urlopen", return_value=mock_response):
        ok, payload, msg = interpreter.interpret(
            "Please pay ₹12,000 to ACC-FRAUD-999 for supplier invoice",
            task_id="TASK-DISP-101",
            user_role="riya",
        )
        # Should fall back to rule-based parser and succeed
        assert ok
        assert payload["action_type"] == "process_payment"
        assert payload["arguments"]["amount"] == 12000.0
        assert payload["arguments"]["bank_account"] == "ACC-FRAUD-999"
        assert payload["task_id"] == "TASK-DISP-101"

